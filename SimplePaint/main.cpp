#include <wx/wx.h>//(окна, элементы интерфейса, события, базовые типы данных)
#include <wx/filedlg.h>//для отображения диалогового окна сохранения файла
#include <vector>//для использования динамических массивов

class PaintFrame : public wxFrame {
public:
    PaintFrame() : wxFrame(nullptr, wxID_ANY, "Простой Paint (wxWidgets)", wxDefaultPosition, wxSize(900, 700)) {//конструктор главного окна, устанавливает заголовок, размер и позицию окна

        wxInitAllImageHandlers();//инициализирует все обработчики изображений, чтобы поддерживать сохранение в формате PNG


        wxBoxSizer* mainSizer = new wxBoxSizer(wxVERTICAL);//создает вертикальный sizer для размещения элементов интерфейса в окне


        wxPanel* toolbarPanel = new wxPanel(this, wxID_ANY);//создает панель для размещения инструментов рисования (кнопок выбора цвета, очистки холста и сохранения рисунка)
        wxBoxSizer* toolsSizer = new wxBoxSizer(wxHORIZONTAL);//создает горизонтальный sizer для размещения инструментов рисования в панели


        wxButton* btnBlack = new wxButton(toolbarPanel, 2001, "Черный");//создает кнопку для выбора черного цвета с уникальным идентификатором 2001
        wxButton* btnRed = new wxButton(toolbarPanel, 2002, "Красный");//создает кнопку для выбора красного цвета с уникальным идентификатором 2002
        wxButton* btnGreen = new wxButton(toolbarPanel, 2003, "Зеленый");//создает кнопку для выбора зеленого цвета с уникальным идентификатором 2003
        wxButton* btnBlue = new wxButton(toolbarPanel, 2004, "Синий");//создает кнопку для выбора синего цвета с уникальным идентификатором 2004
        

        wxButton* btnClear = new wxButton(toolbarPanel, 2005, "Очистить холст");//создает кнопку для очистки холста с уникальным идентификатором 2005
        wxButton* btnSave = new wxButton(toolbarPanel, 2006, "Сохранить в PNG");//создает кнопку для сохранения рисунка в формате PNG с уникальным идентификатором 2006


        btnBlack->Bind(wxEVT_BUTTON, &PaintFrame::OnColorSelect, this);//привязывает обработчик события нажатия кнопки для выбора цвета к каждой кнопке, передавая идентификатор кнопки для определения выбранного цвета в обработчике
        btnRed->Bind(wxEVT_BUTTON, &PaintFrame::OnColorSelect, this);//привязывает обработчик события нажатия кнопки для выбора цвета к каждой кнопке, передавая идентификатор кнопки для определения выбранного цвета в обработчике
        btnGreen->Bind(wxEVT_BUTTON, &PaintFrame::OnColorSelect, this);//привязывает обработчик события нажатия кнопки для выбора цвета к каждой кнопке, передавая идентификатор кнопки для определения выбранного цвета в обработчике
        btnBlue->Bind(wxEVT_BUTTON, &PaintFrame::OnColorSelect, this);//привязывает обработчик события нажатия кнопки для выбора цвета к каждой кнопке, передавая идентификатор кнопки для определения выбранного цвета в обработчике
        btnClear->Bind(wxEVT_BUTTON, &PaintFrame::OnClearCanvas, this);//привязывает обработчик события нажатия кнопки для очистки холста к кнопке очистки
        btnSave->Bind(wxEVT_BUTTON, &PaintFrame::OnSaveCanvas, this);//привязывает обработчик события нажатия кнопки для сохранения рисунка к кнопке сохранения


        toolsSizer->Add(btnBlack, 0, wxALL, 5);//добавляет кнопку выбора черного цвета в горизонтальный sizer с отступами
        toolsSizer->Add(btnRed, 0, wxALL, 5);//добавляет кнопку выбора красного цвета в горизонтальный sizer с отступами
        toolsSizer->Add(btnGreen, 0, wxALL, 5);//добавляет кнопку выбора зеленого цвета в горизонтальный sizer с отступами
        toolsSizer->Add(btnBlue, 0, wxALL, 5);//добавляет кнопку выбора синего цвета в горизонтальный sizer с отступами
        toolsSizer->AddStretchSpacer(1);//добавляет растягивающий элемент в горизонтальный sizer, чтобы отодвинуть кнопки очистки и сохранения к правому краю панели
        toolsSizer->Add(btnClear, 0, wxALL, 5);//добавляет кнопку очистки холста в горизонтальный sizer с отступами
        toolsSizer->Add(btnSave, 0, wxALL, 5);//добавляет кнопку сохранения рисунка в горизонтальный sizer с отступами
        toolbarPanel->SetSizer(toolsSizer);//устанавливает горизонтальный sizer для панели инструментов


        m_canvasPanel = new wxPanel(this, wxID_ANY);//создает панель для рисования, которая будет использоваться в качестве холста для рисования
        m_canvasPanel->SetBackgroundColour(*wxWHITE);//устанавливает белый цвет фона для панели рисования
        m_canvasPanel->SetDoubleBuffered(true);//включает двойную буферизацию для панели рисования, чтобы предотвратить мерцание при рисовании


        m_canvasPanel->Bind(wxEVT_PAINT, &PaintFrame::OnPaint, this);//привязывает обработчик события рисования к панели рисования, который будет вызываться каждый раз, когда панель нуждается в перерисовке
        m_canvasPanel->Bind(wxEVT_LEFT_DOWN, &PaintFrame::OnMouseDown, this);//привязывает обработчик события нажатия левой кнопки мыши к панели рисования, который будет вызываться при начале рисования
        m_canvasPanel->Bind(wxEVT_LEFT_UP, &PaintFrame::OnMouseUp, this);//привязывает обработчик события отпускания левой кнопки мыши к панели рисования, который будет вызываться при завершении рисования
        m_canvasPanel->Bind(wxEVT_MOTION, &PaintFrame::OnMouseMove, this);//привязывает обработчик события движения мыши к панели рисования, который будет вызываться при перемещении мыши во время рисования
        m_canvasPanel->Bind(wxEVT_SIZE, &PaintFrame::OnResize, this);//привязывает обработчик события изменения размера к панели рисования, который будет вызываться при изменении размера окна, чтобы адаптировать холст к новому размеру


        mainSizer->Add(toolbarPanel, 0, wxEXPAND);//добавляет панель инструментов в основной sizer и позволяет ей расширяться по горизонтали
        mainSizer->Add(m_canvasPanel, 1, wxEXPAND | wxALL, 5);//добавляет панель рисования в основной sizer, позволяет ей расширяться и добавляет отступы
        SetSizer(mainSizer);//устанавливает основной sizer для главного окна


        m_currentColour = *wxBLACK;//устанавливает начальный цвет рисования на черный
        m_isDrawing = false;//инициализирует флаг рисования в false, так как рисование еще не началось
    }

private:
    wxPanel* m_canvasPanel;//указатель на панель, которая будет использоваться в качестве холста для рисования
    wxColour m_currentColour;//текущий цвет рисования, который будет изменяться при выборе разных цветов с помощью кнопок
    wxBitmap m_canvasBitmap;//битмап, который будет использоваться для хранения текущего состояния холста и отображаться на панели рисования
    wxPoint m_lastPos;//последняя позиция мыши, которая будет использоваться для рисования линий между предыдущей и текущей позицией мыши
    bool m_isDrawing;//флаг, указывающий, находится ли пользователь в процессе рисования (нажата ли левая кнопка мыши)


    void InitBitmap(int w, int h) {//инициализирует битмап для холста, создавая новый битмап с заданными шириной и высотой, если текущий битмап не существует или его размер меньше нового размера, и копирует существующий битмап на новый, если он уже существует
        if (!m_canvasBitmap.IsOk() || m_canvasBitmap.GetWidth() < w || m_canvasBitmap.GetHeight() < h) {//проверяет, существует ли текущий битмап и достаточно ли он велик для нового размера
            wxBitmap newBitmap(w, h);//создает новый битмап с заданными шириной и высотой
            wxMemoryDC memDC(newBitmap);//создает объект wxMemoryDC для рисования на новом битмапе
            memDC.SetBackground(*wxWHITE_BRUSH);//устанавливает белый цвет фона для нового битмапа
            memDC.Clear();//очищает новый битмап, заполняя его белым цветом

            if (m_canvasBitmap.IsOk()) {//если текущий битмап существует, копирует его содержимое на новый битмап
                memDC.DrawBitmap(m_canvasBitmap, 0, 0);//копирует существующий битмап на новый, начиная с координат (0, 0)
            }
            m_canvasBitmap = newBitmap;//обновляет текущий битмап, присваивая ему новый битмап
        }
    }


    void OnPaint(wxPaintEvent& event) {//обработчик события рисования, который отвечает за отображение текущего состояния холста на панели рисования
        wxPaintDC dc(m_canvasPanel);//создает объект wxPaintDC, привязанный к панели рисования, для выполнения операций рисования на панели
        if (m_canvasBitmap.IsOk()) {//проверяет, существует ли битмап холста, прежде чем пытаться его отобразить
            dc.DrawBitmap(m_canvasBitmap, 0, 0);//рисует битмап холста на панели рисования, начиная с координат (0, 0)
        }
    }


    void OnResize(wxSizeEvent& event) {//обработчик события изменения размера, который вызывается при изменении размера окна, инициализирует битмап для холста с новым размером, чтобы адаптировать холст к новому размеру окна
        wxSize size = m_canvasPanel->GetClientSize();//получает текущий размер клиентской области панели рисования, который может измениться при изменении размера окна
        InitBitmap(size.GetWidth(), size.GetHeight());//инициализирует битмап для холста с новым размером, чтобы адаптировать холст к новому размеру окна
        event.Skip();//передает событие дальше, чтобы обеспечить правильную обработку изменения размера окна
    }


    void OnColorSelect(wxCommandEvent& event) {//обработчик события выбора цвета, который вызывается при нажатии на одну из кнопок выбора цвета и обновляет текущий цвет рисования в зависимости от идентификатора нажатой кнопки
        switch (event.GetId()) {//проверяет идентификатор события, чтобы определить, какая кнопка была нажата, и устанавливает текущий цвет рисования в соответствии с выбранной кнопкой
            case 2001: m_currentColour = *wxBLACK; break;//если нажата кнопка с идентификатором 2001, устанавливает текущий цвет на черный
            case 2002: m_currentColour = *wxRED; break;//если нажата кнопка с идентификатором 2002, устанавливает текущий цвет на красный
            case 2003: m_currentColour = *wxGREEN; break;//если нажата кнопка с идентификатором 2003, устанавливает текущий цвет на зеленый
            case 2004: m_currentColour = *wxBLUE; break;//если нажата кнопка с идентификатором 2004, устанавливает текущий цвет на синий
        }
    }


    void OnClearCanvas(wxCommandEvent& event) {//обработчик события очистки холста, который вызывается при нажатии на кнопку очистки и очищает битмап холста, заполняя его белым цветом, и обновляет панель рисования
        if (m_canvasBitmap.IsOk()) {//проверяет, существует ли битмап холста, прежде чем пытаться его очистить
            wxMemoryDC memDC(m_canvasBitmap);//создает объект wxMemoryDC для рисования на битмапе холста
            memDC.SetBackground(*wxWHITE_BRUSH);//устанавливает белый цвет фона для битмапа холста
            memDC.Clear();//очищает битмап холста, заполняя его белым цветом
            m_canvasPanel->Refresh();//обновляет панель рисования, чтобы отобразить очищенный холст
        }
    }


    void OnSaveCanvas(wxCommandEvent& event) {//обработчик события сохранения рисунка, который вызывается при нажатии на кнопку сохранения и открывает диалоговое окно для выбора места сохранения файла, сохраняет текущий битмап холста в формате PNG и отображает сообщение об успехе или ошибке
        wxFileDialog saveFileDialog(this, "Сохранить рисунок", "", "canvas.png",//создает диалоговое окно для сохранения файла с заголовком "Сохранить рисунок", начальным именем файла "canvas.png" и фильтром для отображения только PNG файлов, а также с флагами для сохранения и подтверждения перезаписи
                                   "PNG файлы (*.png)|*.png", wxFD_SAVE | wxFD_OVERWRITE_PROMPT);//создает диалоговое окно для сохранения файла с заголовком "Сохранить рисунок", начальным именем файла "canvas.png" и фильтром для отображения только PNG файлов, а также с флагами для сохранения и подтверждения перезаписи

        if (saveFileDialog.ShowModal() == wxID_CANCEL)//если пользователь отменяет диалоговое окно, просто возвращаемся из функции, не выполняя сохранение
            return;


        wxImage image = m_canvasBitmap.ConvertToImage();//преобразует текущий битмап холста в объект wxImage, который может быть сохранен в формате PNG
        if (image.SaveFile(saveFileDialog.GetPath(), wxBITMAP_TYPE_PNG)) {//пытается сохранить изображение в выбранном пользователем месте с помощью метода SaveFile, который возвращает true при успешном сохранении и false при ошибке, и отображает соответствующее сообщение
            wxMessageBox("Рисунок успешно сохранен!", "Успех");//показывает диалоговое окно с сообщением об успешном сохранении и заголовком "Успех"
        } else {//если сохранение не удалось, отображаем сообщение об ошибке
            wxMessageBox("Не удалось сохранить файл.", "Ошибка", wxICON_ERROR);//показывает диалоговое окно с сообщением об ошибке и заголовком "Ошибка", а также с иконкой ошибки
        }
    }


    void OnMouseDown(wxMouseEvent& event) {//обработчик события нажатия мыши, который вызывается при начале рисования и устанавливает флаг рисования в true, а также сохраняет начальную позицию мыши для последующего рисования линий
        m_isDrawing = true;//устанавливает флаг рисования в true, так как пользователь начал рисовать, нажав на панель рисования
        m_lastPos = event.GetPosition();//сохраняет начальную позицию мыши, которая будет использоваться для рисования линий между предыдущей и текущей позицией мыши
    }


    void OnMouseUp(wxMouseEvent& event) {//обработчик события отпускания мыши, который вызывается при завершении рисования и устанавливает флаг рисования в false, так как пользователь закончил рисовать, отпустив кнопку мыши
        m_isDrawing = false;//устанавливает флаг рисования в false, так как пользователь закончил рисовать, отпустив кнопку мыши
    }


    void OnMouseMove(wxMouseEvent& event) {//обработчик события движения мыши, который вызывается при перемещении мыши во время рисования и рисует линии на битмапе холста между предыдущей и текущей позицией мыши, если флаг рисования установлен в true, и обновляет панель рисования
        if (m_isDrawing && event.Dragging() && m_canvasBitmap.IsOk()) {//проверяет, находится ли пользователь в процессе рисования (флаг рисования установлен в true), перемещает ли мышь (метод Dragging() возвращает true, если мышь перемещается с зажатой кнопкой) и существует ли битмап холста, прежде чем пытаться рисовать линии на холсте
            wxPoint currentPos = event.GetPosition();//получает текущую позицию мыши, которая будет использоваться для рисования линии от предыдущей позиции до текущей позиции


            wxMemoryDC memDC(m_canvasBitmap);//создает объект wxMemoryDC для рисования на битмапе холста
            memDC.SetPen(wxPen(m_currentColour, 4));//устанавливает перо для рисования линий на холсте с текущим цветом и толщиной 4 пикселя
            memDC.DrawLine(m_lastPos, currentPos);//рисует линию на битмапе холста от предыдущей позиции мыши (m_lastPos) до текущей позиции мыши (currentPos)

            m_lastPos = currentPos;//обновляет последнюю позицию мыши, сохраняя текущую позицию для следующего сегмента линии при дальнейшем перемещении мыши
            m_canvasPanel->Refresh();//обновляет панель рисования, чтобы отобразить новые линии, нарисованные на битмапе холста
        }
    }
};

class PaintApp : public wxApp {//класс приложения, наследующий от wxApp, который является точкой входа в программу
public://переопределяет виртуальную функцию OnInit, которая вызывается при запуске приложения, создает экземпляр главного окна (PaintFrame), отображает его и возвращает true для успешной инициализации приложения
    virtual bool OnInit() {//создает экземпляр главного окна (PaintFrame), отображает его и возвращает true для успешной инициализации приложения
        PaintFrame* frame = new PaintFrame();//создает новый экземпляр главного окна
        frame->Show(true);//отображает окно на экране
        return true;//возвращает true для успешной инициализации приложения
    }
};

wxIMPLEMENT_APP(PaintApp);//макрос, который реализует функцию main и запускает приложение PaintApp